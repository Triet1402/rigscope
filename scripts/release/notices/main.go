// Command notices writes THIRD_PARTY_NOTICES-go.md for the static Rigscope
// binary: the Go standard library and every module in the module graph, with
// the license text shipped in the local module cache.
//
// It never contacts the network. The module graph comes from
//
//	GOPROXY=off go list -m -json all
//
// and each module's license files are read from its cache directory (Dir).
// Output is deterministic: modules are sorted by path, license files by name,
// and no timestamps are written.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// maxLicenseBytes bounds one license file. Every real license is far smaller;
// a larger file is truncated and the truncation is recorded in the output.
const maxLicenseBytes = 512 << 10

type module struct {
	Path     string
	Version  string
	Dir      string
	Main     bool
	Indirect bool
	Replace  *module
}

type notice struct {
	path     string
	version  string
	dir      string
	replaced string
}

func main() {
	output := flag.String("o", "THIRD_PARTY_NOTICES-go.md", "output file")
	root := flag.String("root", ".", "repository root containing go.mod")
	flag.Parse()
	if err := run(*root, *output); err != nil {
		fmt.Fprintf(os.Stderr, "notices: %v\n", err)
		os.Exit(1)
	}
}

func run(root, output string) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	goTool, err := exec.LookPath("go")
	if err != nil {
		return errors.New("go tool is required to read the module graph")
	}
	goroot, err := goEnv(goTool, root, "GOROOT")
	if err != nil {
		return err
	}
	modules, err := moduleGraph(goTool, root)
	if err != nil {
		return err
	}
	linked, err := linkedModules(goTool, root)
	if err != nil {
		return err
	}
	version, err := goEnv(goTool, root, "GOVERSION")
	if err != nil {
		return err
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "# Third-party notices for the Go binary\n\n")
	fmt.Fprintf(&out, "Rigscope 1.0 is distributed as one static Go binary. This file lists the Go\n")
	fmt.Fprintf(&out, "standard library and every module in the module graph, with the license text\n")
	fmt.Fprintf(&out, "shipped in the module cache. The browser UI is a separate bundle; its notices\n")
	fmt.Fprintf(&out, "are in THIRD_PARTY_NOTICES.md.\n\n")
	fmt.Fprintf(&out, "Generated by scripts/release/notices.sh. Do not edit by hand.\n\n")

	stdlibDir := goroot
	stdlibFiles, err := licenseFiles(stdlibDir)
	if err != nil {
		return err
	}
	var stdlib bytes.Buffer
	writeEntry(&stdlib, "Go standard library", version, "", stdlibFiles, stdlibDir)
	out.Write(stdlib.Bytes())

	var uncached []string
	for _, mod := range modules {
		entry := notice{path: mod.Path, version: mod.Version, dir: mod.Dir}
		if mod.Replace != nil {
			if mod.Replace.Dir != "" {
				entry.dir = mod.Replace.Dir
			}
			replacement := mod.Replace.Path
			if mod.Replace.Version != "" {
				replacement += " " + mod.Replace.Version
			}
			entry.replaced = replacement
		}
		if entry.dir == "" {
			if linked[mod.Path] {
				return fmt.Errorf("%s is linked into the release binary but its source is not in the module cache", mod.Path)
			}
			uncached = append(uncached, mod.Path+" "+mod.Version)
			continue
		}
		files, err := licenseFiles(entry.dir)
		if err != nil {
			return fmt.Errorf("%s: %w", mod.Path, err)
		}
		writeEntry(&out, entry.path, entry.version, entry.replaced, files, entry.dir)
	}

	if len(uncached) > 0 {
		fmt.Fprintf(&out, "## Module graph entries without cached source\n\n")
		fmt.Fprintf(&out, "These modules appear in the module graph but are not linked into the release\n")
		fmt.Fprintf(&out, "binary and their source is not in the local module cache, so no license file\n")
		fmt.Fprintf(&out, "was available offline. They are listed for completeness.\n\n")
		for _, entry := range uncached {
			fmt.Fprintf(&out, "- %s\n", entry)
		}
		fmt.Fprintf(&out, "\n")
	}

	if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(output), ".notices-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(out.Bytes()); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), output)
}

func goEnv(goTool, dir, name string) (string, error) {
	command := exec.Command(goTool, "env", name)
	command.Dir = dir
	command.Env = append(os.Environ(), "GOPROXY=off")
	data, err := command.Output()
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			return "", fmt.Errorf("go env %s: %s", name, strings.TrimSpace(string(exit.Stderr)))
		}
		return "", err
	}
	return strings.TrimSpace(string(data)), nil
}

// moduleGraph decodes the JSON stream from `go list -m -json all`. GOPROXY is
// off so a missing module fails instead of being fetched.
func moduleGraph(goTool, dir string) ([]module, error) {
	command := exec.Command(goTool, "list", "-m", "-json", "all")
	command.Dir = dir
	command.Env = append(os.Environ(), "GOPROXY=off")
	stdout, err := command.Output()
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			return nil, fmt.Errorf("go list -m -json all: %s", strings.TrimSpace(string(exit.Stderr)))
		}
		return nil, err
	}
	decoder := json.NewDecoder(bufio.NewReader(bytes.NewReader(stdout)))
	var modules []module
	for {
		var mod module
		if err := decoder.Decode(&mod); errors.Is(err, io.EOF) {
			break
		} else if err != nil {
			return nil, fmt.Errorf("decode module graph: %w", err)
		}
		if mod.Main || mod.Path == "" {
			continue
		}
		modules = append(modules, mod)
	}
	sort.Slice(modules, func(i, j int) bool { return modules[i].Path < modules[j].Path })
	return modules, nil
}

// linkedModules returns the module paths that contribute packages to the
// release binary. A graph-only module without cached source is acceptable only
// when it is not linked; a linked one must be in the cache so its license can
// be included.
func linkedModules(goTool, dir string) (map[string]bool, error) {
	command := exec.Command(goTool, "list", "-deps",
		"-f", "{{with .Module}}{{.Path}}{{end}}", "./cmd/rigscope")
	command.Dir = dir
	command.Env = append(os.Environ(), "GOPROXY=off")
	output, err := command.Output()
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			return nil, fmt.Errorf("go list -deps: %s", strings.TrimSpace(string(exit.Stderr)))
		}
		return nil, err
	}
	linked := map[string]bool{}
	for _, line := range strings.Split(string(output), "\n") {
		if line = strings.TrimSpace(line); line != "" {
			linked[line] = true
		}
	}
	return linked, nil
}

// licenseFiles returns the license-like files below dir, relative to it and
// sorted. Test fixtures and version-control data are skipped.
func licenseFiles(dir string) ([]string, error) {
	if dir == "" {
		return nil, errors.New("module has no cache directory")
	}
	var files []string
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			if path == dir {
				return err
			}
			return nil
		}
		if entry.IsDir() {
			switch entry.Name() {
			case ".git", "testdata", "vendor", "node_modules":
				return filepath.SkipDir
			}
			return nil
		}
		if !entry.Type().IsRegular() || !licenseName(entry.Name()) {
			return nil
		}
		relative, err := filepath.Rel(dir, path)
		if err != nil {
			return nil
		}
		files = append(files, filepath.ToSlash(relative))
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	if len(files) == 0 {
		return nil, errors.New("no license file in the module cache directory")
	}
	return files, nil
}

// licenseName accepts LICENSE, LICENCE, COPYING, COPYRIGHT and NOTICE with an
// optional .md/.txt or hyphen/underscore suffix (LICENSE-SQLITE, LICENSE.txt).
// Code files such as copyright.go are not license texts.
func licenseName(name string) bool {
	upper := strings.ToUpper(name)
	for _, base := range []string{"LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE"} {
		if upper == base {
			return true
		}
		if !strings.HasPrefix(upper, base) {
			continue
		}
		rest := upper[len(base):]
		switch {
		case rest == ".MD" || rest == ".TXT" || rest == ".MARKDOWN":
			return true
		case strings.HasPrefix(rest, "-") || strings.HasPrefix(rest, "_"):
			// License variants such as LICENSE-3RD-PARTY.md or LICENSE_list.
			return true
		}
	}
	return false
}

func writeEntry(out *bytes.Buffer, path, version, replaced string, files []string, dir string) {
	fmt.Fprintf(out, "## %s", path)
	if version != "" {
		fmt.Fprintf(out, " %s", version)
	}
	fmt.Fprintf(out, "\n\n")
	if replaced != "" {
		fmt.Fprintf(out, "Replaced by: %s\n\n", replaced)
	}
	if len(files) == 0 {
		fmt.Fprintf(out, "No license file found in the module cache.\n\n")
		return
	}
	for _, file := range files {
		data, truncated, err := readLicense(filepath.Join(dir, filepath.FromSlash(file)))
		if err != nil {
			fmt.Fprintf(out, "License file `%s` could not be read: %v\n\n", file, err)
			continue
		}
		fmt.Fprintf(out, "License file: `%s`\n\n", file)
		out.Write(bytes.TrimRight(data, "\r\n"))
		out.WriteString("\n")
		if truncated {
			fmt.Fprintf(out, "\n[truncated at %d bytes]\n", maxLicenseBytes)
		}
		fmt.Fprintf(out, "\n")
	}
}

func readLicense(path string) ([]byte, bool, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, false, err
	}
	defer file.Close()
	data, err := io.ReadAll(io.LimitReader(file, maxLicenseBytes+1))
	if err != nil {
		return nil, false, err
	}
	if len(data) > maxLicenseBytes {
		return data[:maxLicenseBytes], true, nil
	}
	return data, false, nil
}
