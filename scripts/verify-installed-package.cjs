#!/usr/bin/env node
/**
 * Verify the package as a consumer actually installs it.
 *
 * Source-tree `npm audit` cannot prove an installed dependency graph is safe:
 * npm `overrides` only apply to the root project, so a published archive can
 * resolve vulnerable transitive versions even when the checkout's lockfile is
 * clean. This script packs the already-built archive, installs it into a
 * throwaway prefix with production dependencies only, audits that installed
 * tree, and starts the packaged hub from those installed files.
 *
 * It never publishes anything, changes the checkout's node_modules, starts a
 * service, or touches developer state. Run it after `npm run verify:package`
 * (or any build) so `.next/` and `dist/` exist.
 *
 * Usage:
 *   node scripts/verify-installed-package.cjs [--root ROOT]
 */
const { spawn, spawnSync } = require("node:child_process");
const {
  existsSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
} = require("node:fs");
const { createInterface } = require("node:readline");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const { parsePackOutput } = require("./verify-package.cjs");
const { verifyBuild } = require("./verify-build.cjs");

