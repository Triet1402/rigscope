  "f84712d2f87d69b7f5baf48ed6e4b0804d67f3000a368f7504e75c6d30422580";
const LISTENING_LINE = /^hub listening on http:\/\/127\.0\.0\.1:(\d+)$/;
const HUB_BOOT_MS = 30_000;
const SAFE_INSTALLED_POSTCSS = "8.5.23";
const npm = process.platform === "win32" ? "npm.cmd" : "npm";

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    ...options,
  });
  if (result.error) throw new Error(`could not run ${command}: ${result.error.message}`);
  return result;
}

function installedEnvironment() {
  const env = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value === undefined) continue;
    if (key === "NODE_ENV" || key.startsWith("HUB_") || key.startsWith("COLLECTOR_")) continue;
    env[key] = value;
  }
  return env;
}

function packBuiltArchive(root, destination) {
  const build = verifyBuild(root);
  if (!build.ok) {
    throw new Error(
      `production artifacts are missing; run "npm run build" first:\n${build.errors.join("\n")}`,
    );
  }
  const result = run(npm, ["pack", "--ignore-scripts", "--json", "--pack-destination", destination], {
    cwd: root,
  });
  if (result.status !== 0) {
    throw new Error(`npm pack failed with status ${result.status}:\n${result.stderr || result.stdout}`);
  }
  const entry = parsePackOutput(result.stdout || "");
  if (!entry?.filename) throw new Error(`npm pack did not report an archive:\n${result.stdout}`);
  const archive = join(destination, entry.filename);
  if (!existsSync(archive)) throw new Error(`npm pack did not create ${entry.filename}`);
  return archive;
}

function installArchive(prefix, archive) {
  const result = run(npm, [
    "install",
    "--prefix", prefix,
    "--omit=dev",
    "--ignore-scripts",
    "--no-audit",
    "--no-fund",
    archive,
  ]);
  if (result.status !== 0) {
    throw new Error(`installing ${archive} failed with status ${result.status}:\n${result.stderr || result.stdout}`);
  }
}

/**
 * @param {string} prefix
 * @returns {{ total: number, high: number, critical: number, moderate: number, low: number, info: number, detail: string }}
 */
function auditInstalled(prefix) {
  const result = run(npm, ["audit", "--omit=dev", "--json"], { cwd: prefix });
  if (result.status !== 0 && result.status !== 1) {
    throw new Error(`npm audit failed with status ${result.status}:\n${result.stderr || result.stdout}`);
  }
  let report;
  try {
    report = JSON.parse(result.stdout || "");
  } catch {
    throw new Error(`npm audit did not return JSON (status ${result.status}):\n${result.stdout}\n${result.stderr}`);
  }
  if (report.metadata?.vulnerabilities === undefined) {
    throw new Error(`npm audit returned no vulnerability summary (status ${result.status}):\n${result.stdout}`);
  }
  const counts = report.metadata.vulnerabilities;
  const detailResult = result.status === 0
    ? result
    : run(npm, ["audit", "--omit=dev"], { cwd: prefix });
  return {
    total: Number(counts.total ?? 0),
    critical: Number(counts.critical ?? 0),
    high: Number(counts.high ?? 0),
    moderate: Number(counts.moderate ?? 0),
    low: Number(counts.low ?? 0),
    info: Number(counts.info ?? 0),
    detail: detailResult.stdout || detailResult.stderr,
  };
}

function installedPackages(nodeModules, name, versions = []) {
  const visitPackage = (directory) => {
    const manifest = join(directory, "package.json");
    if (existsSync(manifest)) {
      try {
        const parsed = JSON.parse(readFileSync(manifest, "utf8"));
        if (parsed.name === name && typeof parsed.version === "string") versions.push(parsed.version);
      } catch {
        // A transient or optional package may have no readable manifest.
      }
    }
    const nested = join(directory, "node_modules");
    if (existsSync(nested)) walk(nested);
  };
  const walk = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name === ".bin") continue;
      const directoryPath = join(directory, entry.name);
      if (entry.name.startsWith("@")) {
        for (const scoped of readdirSync(directoryPath, { withFileTypes: true })) {
          if (scoped.isDirectory()) visitPackage(join(directoryPath, scoped.name));
        }
      } else {
        visitPackage(directoryPath);
      }
    }
  };
  walk(nodeModules);
  return versions;
}

function atLeast(version, minimum) {
  const left = version.split(/[.-]/).map((part) => Number.parseInt(part, 10));
  const right = minimum.split(/[.-]/).map((part) => Number.parseInt(part, 10));
  for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
    const a = Number.isFinite(left[index]) ? left[index] : 0;
    const b = Number.isFinite(right[index]) ? right[index] : 0;
    if (a !== b) return a > b;
  }
  return true;
}

function childOutput(child) {
  const stdout = [];
  const stderr = [];
  const waiters = [];
  const output = createInterface({ input: child.stdout });
  const errors = createInterface({ input: child.stderr });
  output.on("line", (line) => {
    stdout.push(line);
    if (stdout.length > 200) stdout.shift();
    for (let index = waiters.length - 1; index >= 0; index -= 1) {
      if (!waiters[index].predicate(line)) continue;
      waiters.splice(index, 1)[0].resolve(line);
    }
  });
  errors.on("line", (line) => {
    stderr.push(line);
    if (stderr.length > 200) stderr.shift();
  });
  child.once("exit", () => {
    for (const waiter of waiters.splice(0)) {
      waiter.reject(new Error(`process exited before ${waiter.description}`));
    }
  });
  return {
    dump: () => `stdout:\n${stdout.slice(-40).join("\n")}\nstderr:\n${stderr.slice(-40).join("\n")}`,
    waitForLine: (predicate, timeoutMs, description) => {
      const existing = stdout.find(predicate);
      if (existing !== undefined) return Promise.resolve(existing);
      return new Promise((resolveLine, rejectLine) => {
        const waiter = {
          predicate,
          description,
          resolve: (line) => {
            clearTimeout(waiter.timer);
            resolveLine(line);
          },
          reject: (error) => {
            clearTimeout(waiter.timer);
            rejectLine(error);
          },
          timer: setTimeout(() => {
            const index = waiters.indexOf(waiter);
            if (index >= 0) waiters.splice(index, 1);
            rejectLine(new Error(`timed out after ${timeoutMs}ms waiting for ${description}`));
          }, timeoutMs),
        };
        waiters.push(waiter);
      });
    },
  };
}

function stopChild(child, signal = "SIGTERM", graceMs = 8_000) {
  if (child.exitCode !== null || child.signalCode !== null) return Promise.resolve(child.exitCode);
  return new Promise((resolveStop) => {
    const timer = setTimeout(() => {
      child.kill("SIGKILL");
    }, graceMs);
    child.once("exit", (code) => {
      clearTimeout(timer);
      resolveStop(code);
    });
    child.kill(signal);
  });
}

async function verifyRuntime(packageDirectory) {
  const env = installedEnvironment();
  Object.assign(env, {
    NODE_ENV: "production",
    HUB_HOST: "127.0.0.1",
    HUB_PORT: "0",
    HUB_DATABASE_PATH: ":memory:",
    HUB_BROWSER_USERS: JSON.stringify([{
      username: FIXTURE_USERNAME,
      passwordHash: FIXTURE_PASSWORD_HASH,
      machineIds: "*",
    }]),
  });
  const child = spawn(process.execPath, [join(packageDirectory, "dist", "hub.cjs")], {
    cwd: packageDirectory,
    env,
    stdio: ["ignore", "pipe", "pipe"],
  });
  const output = childOutput(child);
  try {
    const line = await output.waitForLine((candidate) => LISTENING_LINE.test(candidate), HUB_BOOT_MS,
      "the packaged hub listening line");
    const port = Number(LISTENING_LINE.exec(line)[1]);
    const baseUrl = `http://127.0.0.1:${port}`;
    const timeout = AbortSignal.timeout(20_000);

    const signIn = await fetch(`${baseUrl}/login`, { signal: timeout });
    if (signIn.status !== 200) throw new Error(`GET /login returned ${signIn.status}\n${output.dump()}`);
    const signInBody = await signIn.text();
    if (!/sign in/i.test(signInBody)) throw new Error(`GET /login did not render the sign-in view\n${output.dump()}`);

    const login = await fetch(`${baseUrl}/api/auth/login`, {
      method: "POST",
      headers: { "Content-Type": "application/json", Origin: baseUrl },
      body: JSON.stringify({ username: FIXTURE_USERNAME, password: FIXTURE_PASSWORD }),
      signal: timeout,
    });
    if (login.status !== 200) throw new Error(`POST /api/auth/login returned ${login.status}\n${output.dump()}`);
    const setCookie = login.headers.get("set-cookie");
    if (!setCookie) throw new Error(`login did not issue a session cookie\n${output.dump()}`);

    const history = await fetch(`${baseUrl}/history`, {
      headers: { cookie: setCookie.split(";", 1)[0] },
      signal: timeout,
    });
    if (history.status !== 200) throw new Error(`GET /history returned ${history.status}\n${output.dump()}`);
    if (!/text\/html/i.test(history.headers.get("content-type") ?? "")) {
      throw new Error(`GET /history returned ${history.headers.get("content-type")}\n${output.dump()}`);
    }
    const historyBody = await history.text();
    if (!/history/i.test(historyBody)) throw new Error(`GET /history did not render the history view\n${output.dump()}`);
  } finally {
    const code = await stopChild(child);
    if (code !== 0) throw new Error(`packaged hub exited with code ${code}\n${output.dump()}`);
  }
}

function verifyVersion(packageDirectory, expectedVersion) {
  const result = run(process.execPath, [join(packageDirectory, "bin", "rigscope.cjs"), "--version"], {
    cwd: packageDirectory,
    env: installedEnvironment(),
  });
  const printed = (result.stdout || "").trim();
  if (result.status !== 0 || printed !== expectedVersion) {
    throw new Error(
      `installed CLI --version expected ${JSON.stringify(expectedVersion)}, got ${JSON.stringify(printed)} ` +
        `(status ${result.status})\n${result.stderr}`,
    );
  }
}

async function verifyInstalledPackage(root = process.cwd(), suppliedArchive) {
  const base = resolve(root);
  const manifest = JSON.parse(readFileSync(join(base, "package.json"), "utf8"));
  const temporary = mkdtempSync(join(tmpdir(), "rigscope-installed-package-"));
  try {
    const archive = suppliedArchive ? resolve(suppliedArchive) : packBuiltArchive(base, temporary);
    const inspection = require('./verify-package.cjs').verifyPackageArchive(archive, {root: base});
    if (!inspection.ok) throw new Error(inspection.errors.join('\n'));
    const prefix = join(temporary, "prefix");
    installArchive(prefix, archive);

    const audit = auditInstalled(prefix);
    if (audit.total !== 0) {
      throw new Error(
        `installed package audit reports ${audit.total} vulnerabilities ` +
          `(${audit.critical} critical, ${audit.high} high, ${audit.moderate} moderate, ${audit.low} low)\n` +
          audit.detail,
      );
    }

    const packageDirectory = join(prefix, "node_modules", manifest.name);
    if (!existsSync(packageDirectory)) {
      throw new Error(`installed package is missing: ${packageDirectory}`);
    }
    const postcssVersions = installedPackages(join(prefix, "node_modules"), "postcss");
    if (postcssVersions.length === 0) throw new Error("installed package did not resolve postcss");
    for (const version of postcssVersions) {
      if (!atLeast(version, SAFE_INSTALLED_POSTCSS)) {
        throw new Error(
          `installed package resolves postcss ${version}; ${SAFE_INSTALLED_POSTCSS} or newer is required`,
        );
      }
    }

    verifyVersion(packageDirectory, manifest.version);
    await verifyRuntime(packageDirectory);
    return {
      audit,
      archive,
      postcssVersions,
      packageDirectory,
    };
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const rootIndex = args.indexOf("--root");
  const root = rootIndex >= 0 ? args[rootIndex + 1] : process.cwd();
  const archiveIndex = args.indexOf('--archive');
  const archive = archiveIndex >= 0 ? args[archiveIndex + 1] : undefined;
  if (archiveIndex >= 0 && !archive) throw new Error('--archive requires a path');
  verifyInstalledPackage(root, archive)
    .then((report) => {
      const vulnerabilities = report.audit;
      console.log(
        `verify-installed-package: installed archive audit ${vulnerabilities.total} vulnerabilities ` +
          `(${vulnerabilities.critical} critical, ${vulnerabilities.high} high, ` +
          `${vulnerabilities.moderate} moderate, ${vulnerabilities.low} low).`,
      );
      console.log(`verify-installed-package: postcss ${report.postcssVersions.join(", ")}.`);
      console.log("verify-installed-package: CLI --version and production sign-in/history smoke passed.");
    })
    .catch((error) => {
      console.error(`verify-installed-package: ${error instanceof Error ? error.message : error}`);
      process.exit(1);
    });
}

